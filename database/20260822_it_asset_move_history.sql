create or replace function public.assign_it_asset_move_id()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_year integer;
  next_value integer;
  actor_name text;
begin
  new.performed_at := coalesce(new.performed_at, timezone('utc', now()));
  target_year := extract(year from (now() at time zone 'Asia/Bangkok'))::integer;

  select coalesce(
    nullif(trim(to_jsonb(p) ->> 'full_name'), ''),
    nullif(trim(to_jsonb(p) ->> 'email'), ''),
    auth.uid()::text
  )
  into actor_name
  from public.profiles p
  where p.id = auth.uid();

  insert into public.it_asset_move_year_sequences (move_year, last_value, updated_at)
  values (target_year, 1, timezone('utc', now()))
  on conflict (move_year) do update
    set last_value = public.it_asset_move_year_sequences.last_value + 1,
        updated_at = timezone('utc', now())
  returning last_value into next_value;

  new.move_id := format('MOVE-%s-%s', target_year, lpad(next_value::text, 4, '0'));
  new.operator_profile_id := auth.uid();
  new.operator_name := coalesce(actor_name, nullif(trim(new.operator_name), ''), auth.uid()::text);
  new.created_by := auth.uid();
  new.created_by_name := coalesce(actor_name, nullif(trim(new.created_by_name), ''), auth.uid()::text);
  new.created_at := timezone('utc', now());
  new.updated_at := new.created_at;
  return new;
end;
$$;

drop trigger if exists trg_assign_it_asset_move_id on public.it_asset_moves;
create trigger trg_assign_it_asset_move_id
before insert on public.it_asset_moves
for each row
execute function public.assign_it_asset_move_id();

create or replace function public.protect_it_asset_move_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_name text;
begin
  if tg_op = 'DELETE' then
    raise exception 'IT asset movement history cannot be deleted';
  end if;

  if old.status = 'cancelled' then
    raise exception 'Cancelled movement history cannot be changed';
  end if;

  if new.status <> 'cancelled' then
    raise exception 'Movement history is immutable; use cancellation instead';
  end if;

  if length(trim(coalesce(new.cancellation_reason, ''))) = 0 then
    raise exception 'Cancellation reason is required';
  end if;

  if (
    to_jsonb(new)
      - 'status'
      - 'cancellation_reason'
      - 'cancelled_at'
      - 'cancelled_by'
      - 'cancelled_by_name'
      - 'updated_at'
  ) is distinct from (
    to_jsonb(old)
      - 'status'
      - 'cancellation_reason'
      - 'cancelled_at'
      - 'cancelled_by'
      - 'cancelled_by_name'
      - 'updated_at'
  ) then
    raise exception 'Only cancellation fields may be changed';
  end if;

  new.cancelled_at := timezone('utc', now());
  new.cancelled_by := auth.uid();
  select coalesce(
    nullif(trim(to_jsonb(p) ->> 'full_name'), ''),
    nullif(trim(to_jsonb(p) ->> 'email'), ''),
    auth.uid()::text
  )
  into actor_name
  from public.profiles p
  where p.id = auth.uid();
  new.cancelled_by_name := coalesce(actor_name, auth.uid()::text);
  new.updated_at := timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists trg_protect_it_asset_move_history on public.it_asset_moves;
