create or replace function public.is_it_asset_move_manager()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(to_jsonb(p) ->> 'role', '')) in ('admin', 'it_support', 'it_manager')
  );
$$;

grant execute on function public.is_it_asset_move_manager() to authenticated;

create table if not exists public.it_asset_move_year_sequences (
  move_year integer primary key,
  last_value integer not null default 0 check (last_value >= 0),
  updated_at timestamptz not null default timezone('utc', now())
);

revoke all on table public.it_asset_move_year_sequences from anon, authenticated;
alter table public.it_asset_move_year_sequences enable row level security;

