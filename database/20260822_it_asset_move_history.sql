  requester_profile_id uuid,
  requester_name text not null default '',
  requester_employee_code text not null default '',
  ticket_reference text not null default '',
  operator_profile_id uuid not null default auth.uid(),
  operator_name text not null default '',
  device_type text not null
    check (device_type in ('pc', 'notebook', 'monitor', 'printer', 'other')),
  custom_device_type text not null default '',
  asset_code text not null check (length(trim(asset_code)) > 0),
  serial_number text not null default '',
  brand_model text not null default '',
  old_user_name text not null default '',
  old_factory text not null default '',
  old_building text not null default '',
  old_floor text not null default '',
  old_department text not null default '',
  old_desk text not null default '',
