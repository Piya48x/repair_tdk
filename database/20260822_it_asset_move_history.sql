  condition_details text not null default '',
  accessories text[] not null default '{}'::text[],
  accessory_other text not null default '',
  before_images jsonb not null default '[]'::jsonb,
  after_images jsonb not null default '[]'::jsonb,
  notes text not null default '',
  status text not null default 'active'
    check (status in ('active', 'cancelled')),
  cancellation_reason text not null default '',
  cancelled_at timestamptz,
  cancelled_by uuid,
  cancelled_by_name text not null default '',
  created_by uuid not null default auth.uid(),
  created_by_name text not null default '',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

