-- Upgrade personal work notes into a richer work journal / personal planning system.
-- Safe to run multiple times.

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text,
  note_date date not null,
  note_time time,
  priority text not null default 'medium',
  status text not null default 'todo',
  reminder_enabled boolean not null default false,
  tag text,
  tags text[] not null default '{}'::text[],
  is_pinned boolean not null default false,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

alter table public.notes
  add column if not exists priority text not null default 'medium',
  add column if not exists status text not null default 'todo',
  add column if not exists reminder_enabled boolean not null default false,
  add column if not exists tag text,
  add column if not exists tags text[] not null default '{}'::text[],
  add column if not exists is_pinned boolean not null default false,
  add column if not exists created_at timestamptz not null default timezone('utc', now()),
  add column if not exists updated_at timestamptz not null default timezone('utc', now());

alter table public.notes
  alter column status set default 'todo',
  alter column priority set default 'medium',
  alter column reminder_enabled set default false,
  alter column is_pinned set default false,
  alter column tags set default '{}'::text[];

alter table public.notes
  drop constraint if exists notes_priority_check,
  drop constraint if exists notes_status_check,
  drop constraint if exists notes_title_not_blank;

update public.notes
set status = case
  when lower(coalesce(status, '')) = 'done' or upper(coalesce(status, '')) = 'DONE' then 'done'
  when lower(coalesce(status, '')) = 'doing' then 'doing'
  else 'todo'
end;

update public.notes
set tags = case
  when coalesce(array_length(tags, 1), 0) > 0 then (
    select coalesce(array_agg(distinct clean_item), '{}'::text[])
    from (
      select trim(item) as clean_item
      from unnest(tags) as item
      where trim(coalesce(item, '')) <> ''
    ) cleaned
  )
  when coalesce(trim(tag), '') <> '' then regexp_split_to_array(regexp_replace(trim(tag), '\s*,\s*', ',', 'g'), ',')
  else '{}'::text[]
end;

update public.notes
set tags = '{}'::text[]
where tags is null;

alter table public.notes
  alter column tags set not null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'notes_priority_check'
      and conrelid = 'public.notes'::regclass
  ) then
    alter table public.notes
      add constraint notes_priority_check
      check (priority in ('low', 'medium', 'high'));
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'notes_status_check'
      and conrelid = 'public.notes'::regclass
  ) then
    alter table public.notes
      add constraint notes_status_check
      check (status in ('todo', 'doing', 'done'));
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'notes_title_not_blank'
      and conrelid = 'public.notes'::regclass
  ) then
    alter table public.notes
      add constraint notes_title_not_blank
      check (length(trim(title)) > 0);
  end if;
end $$;

create index if not exists notes_user_date_idx on public.notes (user_id, note_date desc);
create index if not exists notes_user_status_idx on public.notes (user_id, status);
create index if not exists notes_user_pinned_idx on public.notes (user_id, is_pinned desc, updated_at desc);
create index if not exists notes_tags_gin_idx on public.notes using gin (tags);

alter table public.notes enable row level security;

create or replace function public.set_notes_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists notes_set_updated_at on public.notes;
create trigger notes_set_updated_at
before update on public.notes
for each row
execute function public.set_notes_updated_at();

