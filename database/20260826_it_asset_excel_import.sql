-- Safe Excel import for the IT asset master.
-- Keeps the existing asset UUID, photos and activity history when an Asset Code changes.

begin;

create or replace function public.is_it_asset_import_manager()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(to_jsonb(p) ->> 'role', '')) in ('admin', 'it_support', 'it_manager')
  );
$$;

revoke all on function public.is_it_asset_import_manager() from public;
grant execute on function public.is_it_asset_import_manager() to authenticated;

create table if not exists public.it_asset_code_aliases (
  id bigint generated by default as identity primary key,
  asset_id uuid not null references public.it_assets(id) on delete cascade,
  old_asset_code text not null,
  new_asset_code text not null,
  source_file text not null default '',
  changed_by uuid references auth.users(id) on delete set null default auth.uid(),
  changed_at timestamptz not null default timezone('utc', now()),
  constraint it_asset_code_aliases_codes_check
    check (length(trim(old_asset_code)) > 0 and length(trim(new_asset_code)) > 0),
  constraint it_asset_code_aliases_change_check
    check (lower(trim(old_asset_code)) <> lower(trim(new_asset_code))),
  constraint it_asset_code_aliases_unique
    unique (asset_id, old_asset_code, new_asset_code)
);

create index if not exists it_asset_code_aliases_old_code_idx
  on public.it_asset_code_aliases (lower(old_asset_code), changed_at desc);

create index if not exists it_asset_code_aliases_asset_idx
  on public.it_asset_code_aliases (asset_id, changed_at desc);

alter table public.it_asset_code_aliases enable row level security;

drop policy if exists it_asset_code_aliases_select_policy on public.it_asset_code_aliases;
create policy it_asset_code_aliases_select_policy
  on public.it_asset_code_aliases
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.profiles p
      where p.id = auth.uid()
        and lower(coalesce(to_jsonb(p) ->> 'role', '')) in (
          'admin', 'it_support', 'it_manager', 'executive', 'auditor'
        )
    )
  );

grant select on public.it_asset_code_aliases to authenticated;

create or replace function public.import_it_assets_from_excel(
  p_rows jsonb,
  p_source_files text[] default '{}'::text[]
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  row_json jsonb;
  before_asset public.it_assets%rowtype;
  saved_asset public.it_assets%rowtype;
  match_id uuid;
  collision_id uuid;
  serial_match_id uuid;
  serial_match_count integer;
  target_code text;
  source_code text;
  serial_value text;
  status_value text;
  purchase_value date;
  warranty_value date;
  actor_name text;
  inserted_count integer := 0;
  updated_count integer := 0;
  code_changed_count integer := 0;
begin
  if not public.is_it_asset_import_manager() then
    raise exception 'You do not have permission to import IT assets' using errcode = '42501';
  end if;

  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then
    raise exception 'Import payload must be a JSON array';
  end if;

  if jsonb_array_length(p_rows) = 0 then
    raise exception 'Import payload is empty';
  end if;

  if jsonb_array_length(p_rows) > 2000 then
    raise exception 'Import is limited to 2000 rows per batch';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_rows) item
    group by lower(trim(item ->> 'asset_tag'))
    having count(*) > 1
  ) then
    raise exception 'Duplicate Asset Code found in the selected Excel files';
  end if;

  select coalesce(
    nullif(trim(to_jsonb(p) ->> 'full_name'), ''),
    nullif(trim(to_jsonb(p) ->> 'email'), ''),
    auth.uid()::text
  )
  into actor_name
  from public.profiles p
  where p.id = auth.uid();

  actor_name := coalesce(actor_name, auth.uid()::text);

  for row_json in select value from jsonb_array_elements(p_rows)
  loop
    target_code := upper(regexp_replace(trim(coalesce(row_json ->> 'asset_tag', '')), '\s+', '', 'g'));
    source_code := upper(regexp_replace(trim(coalesce(row_json ->> 'source_asset_tag', '')), '\s+', '', 'g'));
    serial_value := trim(coalesce(row_json ->> 'serial_number', ''));
    match_id := null;
    collision_id := null;
    serial_match_id := null;
    serial_match_count := 0;

    if target_code = '' then
      raise exception 'Asset Code is required at % row %', row_json ->> 'source_file', row_json ->> 'source_row';
    end if;

    if trim(coalesce(row_json ->> 'asset_name', '')) = '' then
      raise exception 'Asset name is required for %', target_code;
    end if;

    if coalesce(row_json ->> 'match_asset_id', '') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
      match_id := (row_json ->> 'match_asset_id')::uuid;
      if not exists (select 1 from public.it_assets where id = match_id) then
        match_id := null;
      end if;
    end if;

    if match_id is null and source_code <> '' then
      select a.id
      into match_id
      from public.it_assets a
      where lower(trim(a.asset_tag)) = lower(source_code)
      limit 1;
    end if;

    if match_id is null then
      select a.id
      into match_id
      from public.it_assets a
      where lower(trim(a.asset_tag)) = lower(target_code)
      limit 1;
    end if;

    if match_id is null and serial_value <> '' then
      select count(*)::integer, (array_agg(a.id order by a.created_at))[1]
      into serial_match_count, serial_match_id
      from public.it_assets a
      where lower(trim(coalesce(a.serial_number, ''))) = lower(serial_value);

      if serial_match_count = 1 then
        match_id := serial_match_id;
      end if;
    end if;

    select a.id
    into collision_id
    from public.it_assets a
    where lower(trim(a.asset_tag)) = lower(target_code)
      and (match_id is null or a.id <> match_id)
    limit 1;

    if collision_id is not null then
      raise exception 'Asset Code % is already used by another asset', target_code;
    end if;

    status_value := case lower(trim(coalesce(row_json ->> 'status', '')))
      when 'in_use' then 'in_use'
      when 'assigned' then 'assigned'
      when 'spare' then 'spare'
      when 'available' then 'available'
      when 'repair' then 'repair'
      when 'broken' then 'broken'
      when 'lost' then 'lost'
      when 'retired' then 'retired'
      else 'in_use'
    end;

    purchase_value := case
      when coalesce(row_json ->> 'purchase_date', '') ~ '^\d{4}-\d{2}-\d{2}$'
        then (row_json ->> 'purchase_date')::date
      else null
    end;
    warranty_value := case
      when coalesce(row_json ->> 'warranty_end_date', '') ~ '^\d{4}-\d{2}-\d{2}$'
        then (row_json ->> 'warranty_end_date')::date
      else null
    end;

    if match_id is not null then
      select * into before_asset from public.it_assets where id = match_id for update;

      update public.it_assets
      set
        asset_tag = target_code,
        asset_name = coalesce(nullif(trim(row_json ->> 'asset_name'), ''), before_asset.asset_name),
        asset_category = coalesce(nullif(trim(row_json ->> 'asset_category'), ''), before_asset.asset_category, 'Other'),
        brand = coalesce(nullif(trim(row_json ->> 'brand'), ''), before_asset.brand),
        model = coalesce(nullif(trim(row_json ->> 'model'), ''), before_asset.model),
        serial_number = coalesce(nullif(trim(row_json ->> 'serial_number'), ''), before_asset.serial_number),
        status = status_value,
        location = coalesce(nullif(trim(row_json ->> 'location'), ''), before_asset.location),
        owner_name = coalesce(nullif(trim(row_json ->> 'owner_name'), ''), before_asset.owner_name),
        purchase_date = coalesce(purchase_value, before_asset.purchase_date),
        warranty_end_date = coalesce(warranty_value, before_asset.warranty_end_date),
        notes = coalesce(nullif(trim(row_json ->> 'notes'), ''), before_asset.notes),
        updated_at = timezone('utc', now())
      where id = match_id
      returning * into saved_asset;

      if lower(trim(before_asset.asset_tag)) <> lower(target_code) then
        insert into public.it_asset_code_aliases (
          asset_id, old_asset_code, new_asset_code, source_file, changed_by
        ) values (
          saved_asset.id,
          before_asset.asset_tag,
          target_code,
          coalesce(row_json ->> 'source_file', array_to_string(p_source_files, ', '), ''),
          auth.uid()
        ) on conflict do nothing;
        code_changed_count := code_changed_count + 1;
      else
        updated_count := updated_count + 1;
      end if;

      insert into public.it_asset_activity_logs (
        asset_id, action, summary, changes, snapshot, created_by, created_by_name
      ) values (
        saved_asset.id,
        'updated',
        'Imported from Excel without replacing the asset record',
        jsonb_build_object(
          'source', 'asset_excel_import',
          'source_file', coalesce(row_json ->> 'source_file', ''),
          'source_row', row_json ->> 'source_row',
          'old_asset_code', before_asset.asset_tag,
          'new_asset_code', saved_asset.asset_tag,
          'before', to_jsonb(before_asset)
        ),
        to_jsonb(saved_asset),
        auth.uid(),
        actor_name
      );
    else
      insert into public.it_assets (
        asset_tag, asset_name, asset_category, brand, model, serial_number,
        status, location, owner_name, purchase_date, warranty_end_date, notes,
        created_by, created_at, updated_at
      ) values (
        target_code,
        trim(row_json ->> 'asset_name'),
        coalesce(nullif(trim(row_json ->> 'asset_category'), ''), 'Other'),
        nullif(trim(row_json ->> 'brand'), ''),
        nullif(trim(row_json ->> 'model'), ''),
        nullif(trim(row_json ->> 'serial_number'), ''),
        status_value,
        nullif(trim(row_json ->> 'location'), ''),
        nullif(trim(row_json ->> 'owner_name'), ''),
        purchase_value,
        warranty_value,
        nullif(trim(row_json ->> 'notes'), ''),
        auth.uid(),
        timezone('utc', now()),
        timezone('utc', now())
      ) returning * into saved_asset;

      insert into public.it_asset_activity_logs (
        asset_id, action, summary, changes, snapshot, created_by, created_by_name
      ) values (
        saved_asset.id,
        'created',
        'Created from Asset Excel import',
        jsonb_build_object(
          'source', 'asset_excel_import',
          'source_file', coalesce(row_json ->> 'source_file', ''),
          'source_row', row_json ->> 'source_row'
        ),
        to_jsonb(saved_asset),
        auth.uid(),
        actor_name
      );
      inserted_count := inserted_count + 1;
    end if;
  end loop;

  return jsonb_build_object(
    'total', jsonb_array_length(p_rows),
    'code_changed', code_changed_count,
    'updated', updated_count,
    'inserted', inserted_count,
    'source_files', to_jsonb(coalesce(p_source_files, '{}'::text[]))
  );
end;
$$;

revoke all on function public.import_it_assets_from_excel(jsonb, text[]) from public;
grant execute on function public.import_it_assets_from_excel(jsonb, text[]) to authenticated;

create or replace function public.resolve_it_asset_code(p_code text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select a.asset_tag
  from public.it_asset_code_aliases code_alias
  join public.it_assets a on a.id = code_alias.asset_id
  where lower(trim(code_alias.old_asset_code)) = lower(trim(coalesce(p_code, '')))
    and exists (
      select 1
      from public.profiles p
      where p.id = auth.uid()
        and lower(coalesce(to_jsonb(p) ->> 'role', '')) in (
          'admin', 'it_support', 'it_manager', 'executive', 'auditor'
        )
    )
  order by code_alias.changed_at desc
  limit 1;
$$;

revoke all on function public.resolve_it_asset_code(text) from public;
grant execute on function public.resolve_it_asset_code(text) to authenticated;

comment on table public.it_asset_code_aliases is
  'Maps retired temporary Asset Tags to the current Excel Asset Code without rewriting history.';

comment on function public.import_it_assets_from_excel(jsonb, text[]) is
  'Transactional IT asset Excel import. Updates existing UUIDs and never deletes asset records.';

notify pgrst, 'reload schema';

commit;
