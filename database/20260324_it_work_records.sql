create or replace function public.is_it_work_record_manager()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and lower(coalesce(to_jsonb(p) ->> 'role', '')) in ('admin', 'it_support', 'it_manager')
  );
$$;

grant execute on function public.is_it_work_record_manager() to authenticated;

create table if not exists public.it_work_records (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) > 0),
  job_type text not null check (length(trim(job_type)) > 0),
  work_status text not null default 'completed'
    check (work_status in ('pending', 'in_progress', 'completed')),
  performed_at timestamptz not null default timezone('utc', now()),
  location text not null default '',
  reference_code text not null default '',
  requester_name text not null default '',
  department text not null default '',
  device_details text not null default '',
  description text not null default '',
  result_summary text not null default '',
  evidence_images jsonb not null default '[]'::jsonb
    check (jsonb_typeof(evidence_images) = 'array'),
  created_by uuid not null default auth.uid(),
  created_by_name text not null default '',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_it_work_records_performed_at
  on public.it_work_records (performed_at desc);

create index if not exists idx_it_work_records_job_type
  on public.it_work_records (job_type);

create index if not exists idx_it_work_records_status
  on public.it_work_records (work_status);

alter table public.it_work_records enable row level security;

create or replace function public.set_it_work_records_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists trg_it_work_records_updated_at on public.it_work_records;
create trigger trg_it_work_records_updated_at
before update on public.it_work_records
for each row
execute function public.set_it_work_records_updated_at();

drop policy if exists it_work_records_select_policy on public.it_work_records;
create policy it_work_records_select_policy
  on public.it_work_records
  for select
  to authenticated
  using (public.is_it_work_record_manager());

drop policy if exists it_work_records_insert_policy on public.it_work_records;
create policy it_work_records_insert_policy
  on public.it_work_records
  for insert
  to authenticated
  with check (
    public.is_it_work_record_manager()
    and created_by = auth.uid()
  );

drop policy if exists it_work_records_update_policy on public.it_work_records;
create policy it_work_records_update_policy
  on public.it_work_records
  for update
  to authenticated
  using (public.is_it_work_record_manager())
  with check (public.is_it_work_record_manager());

drop policy if exists it_work_records_delete_policy on public.it_work_records;
create policy it_work_records_delete_policy
  on public.it_work_records
  for delete
  to authenticated
  using (public.is_it_work_record_manager());

